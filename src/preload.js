const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('bridge', {
  getState: () => ipcRenderer.invoke('state:get'),
  peerList: () => ipcRenderer.invoke('peer:list'),
  peerInvite: () => ipcRenderer.invoke('peer:invite'),
  peerAdd: (name, invite) => ipcRenderer.invoke('peer:add', name, invite),
  peerRemove: id => ipcRenderer.invoke('peer:remove', id),
  peerRekey: () => ipcRenderer.invoke('peer:rekey'),
  peerStatus: id => ipcRenderer.invoke('peer:status', id),
  peerMessages: id => ipcRenderer.invoke('peer:messages', id),
  peerSend: (id, text) => ipcRenderer.invoke('peer:send', id, text),
  peerScreen: id => ipcRenderer.invoke('peer:screen', id),
  peerCommand: (id, cmd) => ipcRenderer.invoke('peer:command', id, cmd),
  peerInput: (id, data) => ipcRenderer.invoke('peer:input', id, data),
  peerShare: yes => ipcRenderer.invoke('peer:share', yes),
  peerGrant: minutes => ipcRenderer.invoke('peer:grant', minutes),
  peerRevoke: () => ipcRenderer.invoke('peer:revoke'),
  onPeerUpdate: callback => ipcRenderer.on('peer:update', () => callback()),
  saveSettings: (settings) => ipcRenderer.invoke('settings:save', settings),
  chooseFolder: () => ipcRenderer.invoke('folder:choose'),
  listMountedDrives: () => ipcRenderer.invoke('drives:list'),
  inspectFolder: (folderPath) => ipcRenderer.invoke('folder:inspect', folderPath),
  startLocal: () => ipcRenderer.invoke('local:start'),
  stopLocal: () => ipcRenderer.invoke('local:stop'),
  startBrowser: () => ipcRenderer.invoke('browser:start'),
  stopBrowser: () => ipcRenderer.invoke('browser:stop'),
  startMeta: () => ipcRenderer.invoke('meta:start'),
  stopMeta: () => ipcRenderer.invoke('meta:stop'),
  restartAll: () => ipcRenderer.invoke('servers:restart-all'),
  checkForUpdates: () => ipcRenderer.invoke('update:check'),
  downloadUpdate: () => ipcRenderer.invoke('update:download'),
  installUpdate: () => ipcRenderer.invoke('update:install'),
  getUpdateState: () => ipcRenderer.invoke('update:get-state'),
  previewDiagnostics: () => ipcRenderer.invoke('diagnostics:preview'),
  copyDiagnostics: () => ipcRenderer.invoke('diagnostics:copy'),
  reportDiagnostics: () => ipcRenderer.invoke('diagnostics:github'),
  openExternal: (url) => ipcRenderer.invoke('open:external', url),
  onState: (cb) => ipcRenderer.on('state:update', (_e, state) => cb(state)),
  onLog: (cb) => ipcRenderer.on('log:update', (_e, line) => cb(line)),
  onUpdateState: (cb) => ipcRenderer.on('update:state', (_e, state) => cb(state))
});